#!/usr/bin/env python3
"""用 OpenCC 生成 internal/norm/t2s.go 的繁→简单字对照表（仅一对一单字映射）。
用法: pip install opencc-python-reimplemented && python3 tools/gen_t2s.py
"""
import opencc

c = opencc.OpenCC("t2s")
trad, simp = [], []
for cp in list(range(0x3400, 0x4DC0)) + list(range(0x4E00, 0xA000)):
    ch = chr(cp)
    out = c.convert(ch)
    if len(out) == 1 and out != ch:
        trad.append(ch)
        simp.append(out)

with open("internal/norm/t2s.go", "w", encoding="utf8") as f:
    f.write("// Code generated by tools/gen_t2s.py; DO NOT EDIT.\n\n")
    f.write("package norm\n\n")
    f.write("// 繁体 → 简体单字对照（一对一字符映射，保证归一化前后长度不变）。\n")
    f.write('const tradChars = "%s"\n' % "".join(trad))
    f.write('const simpChars = "%s"\n\n' % "".join(simp))
    f.write('''var t2s = buildT2S()

func buildT2S() map[rune]rune {
	tr, sr := []rune(tradChars), []rune(simpChars)
	m := make(map[rune]rune, len(tr))
	for i := range tr {
		m[tr[i]] = sr[i]
	}
	return m
}
''')
print(len(trad))
